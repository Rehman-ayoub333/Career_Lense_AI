'use client'

import { Download } from 'lucide-react'
import React from 'react'

import type { AnalysisSession } from '@/types'

import { BreakdownBars } from './BreakdownBars'
import { KeyActions } from './KeyActions'
import { ScoreGauge } from './ScoreGauge'
import { ShareCard } from './ShareCard'

interface ScorePanelProps {
  session: AnalysisSession
  onNewAnalysis: () => void
}

export function ScorePanel({ session, onNewAnalysis }: ScorePanelProps) {
  const { result, mode, rewrite, jobTitle, coverLetter } = session

  function handleDownload() {
    const separator = '─'.repeat(50)
    const lines = [
      'CAREERLENS AI — OPTIMIZED CV EXPORT',
      separator,
      '',
      `Role: ${jobTitle}`,
      `Mode: ${mode === 'scholarship' ? 'Scholarship' : 'Job Description'}`,
      `Match Score: ${result.score}/100 — ${result.verdict}`,
      `Generated: ${new Date().toLocaleDateString('en-US', { year: 'numeric', month: 'long', day: 'numeric' })}`,
      '',
      separator,
      'REWRITTEN CV BULLETS',
      separator,
      '',
      ...rewrite.rewritten_bullets.map((bullet, i) => `  ${i + 1}. ${bullet}`),
      '',
      separator,
      'KEY ACTIONS',
      separator,
      '',
      ...result.key_actions.map((action, i) => `  ${i + 1}. ${action}`),
      '',
      separator,
      'SKILLS ANALYSIS',
      separator,
      '',
      `  Matched: ${result.skills_matched.join(', ') || 'None detected'}`,
      `  Missing: ${result.skills_missing.join(', ') || 'None'}`,
      ...(result.skills_extra.length > 0 ? [`  Bonus:   ${result.skills_extra.join(', ')}`] : []),
      '',
      separator,
      'COVER LETTER',
      separator,
      '',
      coverLetter,
      '',
      separator,
      '',
      'Generated by CareerLens AI — careerlens.vercel.app',
    ]

    const blob = new Blob([lines.join('\n')], { type: 'text/plain;charset=utf-8' })
    const url = URL.createObjectURL(blob)
    const anchor = document.createElement('a')
    anchor.href = url
    anchor.download = `careerlens-${jobTitle.slice(0, 30).replace(/[^a-zA-Z0-9]/g, '-').toLowerCase()}.txt`
    anchor.click()
    URL.revokeObjectURL(url)
  }

  return (
    <aside
      data-testid="score-panel"
      className="rounded-[var(--radius-lg)] border border-[hsl(var(--card-border))] bg-[hsl(var(--card))] p-4 lg:sticky lg:top-20 lg:w-[300px]"
    >
      <div className="space-y-4">
        <ScoreGauge score={result.score} />

        <div>
          <div data-testid="score-verdict" className="text-lg font-semibold text-text-primary">
            {result.verdict}
          </div>
          <p className="mt-1 text-sm text-text-muted">{result.verdict_note}</p>
        </div>

        <BreakdownBars result={result} mode={mode} />

        <div>
          <div className="mb-2 text-sm font-semibold text-text-primary">Key actions</div>
          <KeyActions items={result.key_actions} />
        </div>

        <div className="grid gap-2">
          <button
            data-testid="new-analysis-button"
            type="button"
            onClick={onNewAnalysis}
            className="rounded-full border border-[hsl(var(--card-border))] bg-[hsl(var(--card))] px-3 py-2 text-sm font-semibold text-text-primary transition-all duration-200 hover:bg-[hsl(var(--card-hover))] hover:border-[hsl(var(--text-subtle))] active:scale-[0.98]"
          >
            New Analysis
          </button>

          <ShareCard session={session} />

          <button
            data-testid="download-button"
            type="button"
            onClick={handleDownload}
            className="inline-flex items-center justify-center gap-2 rounded-full border border-[hsl(var(--card-border))] bg-transparent px-3 py-2 text-sm font-semibold text-text-muted transition hover:text-text-primary"
          >
            <Download className="h-4 w-4" />
            Download Report
          </button>
        </div>
      </div>
    </aside>
  )
}
